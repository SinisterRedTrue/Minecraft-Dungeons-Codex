/**
 * Coverage report (`[ Plans ]/04-DATA-PIPELINE.md` "Coverage report"). The structured data lives
 * in `data/reports/coverage-{game}.json` (merged category by category, so a one-category sync
 * keeps the others); the Markdown file next to it is rendered from it. `data:validate` reads the
 * Markdown's "Unresolved references" bullets (D-037).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { GAMES, type GameId } from '@/config/games';

const COVERAGE_GATE = 0.98;

export interface CategoryReport {
  category: string;
  expected: number;
  expectedNote: string;
  parsed: number;
  valid: number;
  dropped: { name: string; reason: string }[];
  partial: { id: string; missing: string[] }[];
  missingImages: { id: string; file: string; reason: string }[];
  slugCollisions: { name: string; slug: string }[];
  overridesApplied: { slug: string; field: string; reason: string }[];
  overridesUnmatched: string[];
  unresolved: { value: string; usedBy: string[] }[];
  droppedRefs: { entity: string; message: string }[];
  notes: string[];
}

export interface GameReport {
  game: GameId;
  categories: Record<string, CategoryReport>;
}

export const coverageRatio = (c: Pick<CategoryReport, 'expected' | 'valid'>) =>
  c.expected === 0 ? 1 : c.valid / c.expected;

export const meetsGate = (c: Pick<CategoryReport, 'expected' | 'valid'>) =>
  coverageRatio(c) >= COVERAGE_GATE;

const files = (reportsDir: string, game: GameId) => ({
  json: path.join(reportsDir, `coverage-${game}.json`),
  md: path.join(reportsDir, `coverage-${game}.md`),
});

export function loadReport(reportsDir: string, game: GameId): GameReport {
  const { json } = files(reportsDir, game);
  if (!existsSync(json)) return { game, categories: {} };
  return JSON.parse(readFileSync(json, 'utf8')) as GameReport;
}

export function saveReport(reportsDir: string, report: GameReport): void {
  const { json, md } = files(reportsDir, report.game);
  const order = GAMES[report.game].categories as readonly string[];
  const categories = Object.fromEntries(
    Object.entries(report.categories).sort(([a], [b]) => order.indexOf(a) - order.indexOf(b)),
  );
  const sorted: GameReport = { game: report.game, categories };
  mkdirSync(reportsDir, { recursive: true });
  writeFileSync(json, `${JSON.stringify(sorted, null, 2)}\n`, 'utf8');
  writeFileSync(md, renderMarkdown(sorted), 'utf8');
}

const pct = (n: number) => `${(n * 100).toFixed(1)} %`;

function section(title: string, items: string[], level = 3): string[] {
  if (items.length === 0) return [];
  return [`${'#'.repeat(level)} ${title} (${items.length})`, '', ...items, ''];
}

export function renderMarkdown(report: GameReport): string {
  const cats = Object.values(report.categories);
  const out: string[] = [
    `# Coverage report: ${GAMES[report.game].name} (${report.game})`,
    '',
    `Gate: valid ÷ expected ≥ ${pct(COVERAGE_GATE)} in every category. Generated by \`npm run data:sync\`; do not edit by hand.`,
    '',
    '| Category | Expected | Parsed | Valid | Coverage | Gate | Partial | Dropped |',
    '|---|---:|---:|---:|---:|:-:|---:|---:|',
    ...cats.map(
      (c) =>
        `| ${c.category} | ${c.expected} | ${c.parsed} | ${c.valid} | ${pct(coverageRatio(c))} | ${meetsGate(c) ? '✅' : '❌'} | ${c.partial.length} | ${c.dropped.length} |`,
    ),
    '',
  ];

  // The validator reads these bullets: one per raw value, the value in backticks (D-037).
  const unresolved = new Map<string, Set<string>>();
  for (const c of cats) {
    for (const u of c.unresolved) {
      const set = unresolved.get(u.value) ?? new Set<string>();
      for (const id of u.usedBy) set.add(id);
      unresolved.set(u.value, set);
    }
  }
  out.push('## Unresolved references', '');
  if (unresolved.size === 0) out.push('None.', '');
  else {
    out.push(
      'Raw text kept in `locations` / `drops` because no entity has that name. Each is listed once.',
      '',
      ...[...unresolved]
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([value, usedBy]) => `- \`${value}\` — used by ${[...usedBy].sort().join(', ')}`),
      '',
    );
  }

  for (const c of cats) {
    out.push(`## ${c.category}`, '');
    out.push(
      `- Expected **${c.expected}** (${c.expectedNote}); parsed **${c.parsed}**; valid **${c.valid}** (${pct(coverageRatio(c))}).`,
    );
    for (const note of c.notes) out.push(`- ${note}`);
    out.push('');
    out.push(
      ...section(
        'Dropped records',
        c.dropped.map((d) => `- ${d.name}: ${d.reason}`),
      ),
    );
    out.push(
      ...section(
        'Partial entities (missing recommended fields)',
        c.partial.map((p) => `- ${p.id}: ${p.missing.join(', ')}`),
      ),
    );
    out.push(
      ...section(
        'Missing images',
        c.missingImages.map((m) => `- ${m.id}: ${m.file} (${m.reason})`),
      ),
    );
    out.push(
      ...section(
        'Slug collisions',
        c.slugCollisions.map((s) => `- ${s.name} → ${s.slug}`),
      ),
    );
    out.push(
      ...section(
        'References dropped (id-only fields)',
        c.droppedRefs.map((d) => `- ${d.entity}: ${d.message}`),
      ),
    );
    out.push(
      ...section(
        'Overrides applied',
        c.overridesApplied.map((o) => `- ${o.slug}.${o.field}: ${o.reason}`),
      ),
    );
    out.push(
      ...section(
        'Overrides that matched nothing',
        c.overridesUnmatched.map((s) => `- ${s}`),
      ),
    );
  }
  return `${out
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trimEnd()}\n`;
}
